'use strict';

// Shared helpers for migrations. Kept outside migrations/ so sequelize-cli
// does not try to run this file as a migration.
const { DataTypes, Op, Sequelize } = require('sequelize');

const pk = () => ({
  type: DataTypes.BIGINT,
  primaryKey: true,
  allowNull: false,
  autoIncrement: true,
  autoIncrementIdentity: true, // GENERATED BY DEFAULT AS IDENTITY
});

const createdAt = () => ({
  created_at: {
    type: DataTypes.DATE,
    allowNull: false,
    defaultValue: Sequelize.literal('CURRENT_TIMESTAMP'),
  },
});

const timestamps = () => ({
  ...createdAt(),
  updated_at: {
    type: DataTypes.DATE,
    allowNull: false,
    defaultValue: Sequelize.literal('CURRENT_TIMESTAMP'),
  },
});

const foreignKey = (queryInterface, transaction, { table, name, column, refTable, onDelete }) =>
  queryInterface.addConstraint(table, {
    type: 'foreign key',
    name,
    fields: [column],
    references: { table: refTable, field: 'id' },
    onDelete,
    transaction,
  });

const check = (queryInterface, transaction, { table, name, fields, where }) =>
  queryInterface.addConstraint(table, { type: 'check', name, fields, where, transaction });

const unique = (queryInterface, transaction, { table, name, fields }) =>
  queryInterface.addConstraint(table, { type: 'unique', name, fields, transaction });

const oneOf = (values) => ({ [Op.in]: values });
const gte = (value) => ({ [Op.gte]: value });
const gt = (value) => ({ [Op.gt]: value });

const ORDER_STATUSES = [
  'pending',
  'confirmed',
  'preparing',
  'ready',
  'delivering',
  'completed',
  'cancelled',
];

module.exports = {
  DataTypes,
  Op,
  Sequelize,
  pk,
  createdAt,
  timestamps,
  foreignKey,
  check,
  unique,
  oneOf,
  gte,
  gt,
  ORDER_STATUSES,
};
